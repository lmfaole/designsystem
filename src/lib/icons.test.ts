import { strict as assert } from "node:assert"
import { readFileSync, readdirSync } from "node:fs"
import { join, relative } from "node:path"
import { test } from "node:test"

import { ICON_GROUPS, ICONS, MIRRORED_ICONS } from "./icons.ts"

const src = join(import.meta.dirname, "..")

const files = (directory: string): string[] =>
  readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const path = join(directory, entry.name)
    return entry.isDirectory() ? files(path) : /\.tsx?$/.test(entry.name) ? [path] : []
  })

test("every icon is named for a meaning, in lower-case words joined by dashes", () => {
  for (const name of Object.keys(ICONS)) assert.match(name, /^[a-z]+(?:-[a-z]+)*$/, name)
})

test("every meaning has shapes, and no two meanings share a glyph", () => {
  const shapes = Object.entries(ICONS).map(([name, nodes]) => {
    assert.ok(nodes.length > 0, `${name} has no shapes`)
    return JSON.stringify(nodes)
  })
  assert.equal(new Set(shapes).size, shapes.length, "two meanings use the same glyph: one of them should have its own, or be the other")
})

test("the groups list every meaning once, and the mirrored ones exist", () => {
  const listed = ICON_GROUPS.flatMap(([, names]) => names)
  assert.equal(new Set(listed).size, listed.length, "a meaning is in two groups")
  assert.deepEqual([...listed].toSorted(), Object.keys(ICONS).toSorted(), "regenerate with `npm run icons`")
  for (const name of MIRRORED_ICONS) assert.ok(name in ICONS, `${name} is mirrored but is not a meaning`)
})

test("the shapes on disk are the ones the set says: `npm run icons` has been run", () => {
  const generated = readFileSync(join(src, "lib", "icon-nodes.ts"), "utf8")
  const set = readFileSync(join(src, "..", "scripts", "icon-set.mjs"), "utf8")
  const meanings = [...set.matchAll(/^\s+\["([a-z0-9-]+)", "[a-z0-9-]+"\],?$/gm)].map((match) => match[1])
  assert.deepEqual(meanings.toSorted(), Object.keys(ICONS).toSorted())
  assert.match(generated, /Generated by scripts\/generate-icons\.mjs/)
})

test("an icon is drawn by CSS: no inline colour, and a size, a tone and a mirror from the stylesheet", () => {
  const css = readFileSync(join(src, "icon.css"), "utf8")
  assert.match(css, /--icon-size/)
  assert.match(css, /:dir\(rtl\)/)
  assert.match(css, /currentColor/)
  assert.doesNotMatch(readFileSync(join(src, "components", "icon.tsx"), "utf8"), /style=|fill="|stroke="/)
})

test("a page imports icons from lib/icons.ts, never from lucide-react", () => {
  const direct = files(src)
    .filter((file) => !file.endsWith("lib/icons.ts") && !relative(src, file).startsWith("components/ui/"))
    .filter((file) => /from\s+["']lucide-react["']/.test(readFileSync(file, "utf8")))
    .map((file) => relative(src, file))
  assert.deepEqual(direct, [], "import from ../lib/icons (and add the meaning to ICONS) instead of lucide-react")
})

test("an icon is hidden from a screen reader unless it is given a label, and takes no class of its own", () => {
  const icon = readFileSync(join(src, "components/icon.tsx"), "utf8")
  assert.match(icon, /"aria-hidden": true/)
  assert.match(icon, /role: "img", "aria-label": label/)
  assert.doesNotMatch(icon, /className\?:|style\?:/)
})
