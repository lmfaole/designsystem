// Writes `src/lib/icon-nodes.ts`: the shapes of every icon meaning in `scripts/icon-set.mjs` as plain data, read from the Lucide package
// (ISC licence). The page then draws an `<svg>` of its own from the data; no icon component and no icon library runs in the browser.
// Run it with `npm run icons` after changing the set.
import { readFileSync, writeFileSync } from "node:fs"
import { join } from "node:path"

import { ICON_SET, MIRRORED } from "./icon-set.mjs"

const lucide = join(import.meta.dirname, "..", "node_modules", "lucide-react", "dist", "esm", "icons")
const camel = (name) => name.replace(/-([a-z])/g, (_, letter) => letter.toUpperCase())

/** The `node` list of one Lucide icon file: `[["path", { d: "…", key: "…" }], …]`. */
function shapesOf(file) {
  const source = readFileSync(join(lucide, `${file}.mjs`), "utf8")
  // Some names are only aliases of another icon file.
  const alias = /export\s*\{[^}]*\}\s*from\s*['"]\.\/([a-z0-9-]+)\.mjs['"]/.exec(source) ?? /import\s+\w+\s+from\s+['"]\.\/([a-z0-9-]+)\.mjs['"]/.exec(source)
  if (alias !== null && !source.includes("const __iconData")) return shapesOf(alias[1])
  const start = source.indexOf("const __iconData = ")
  const end = source.indexOf("\n};", start)
  if (start === -1 || end === -1) throw new Error(`no shapes in lucide icon ${file}`)
  const nodes = new Function(`return ${source.slice(start + "const __iconData = ".length, end + 2)}`)().node
  return nodes.map(([tag, attributes]) => [tag, Object.fromEntries(Object.entries(attributes).filter(([name]) => name !== "key").map(([name, value]) => [camel(name), String(value)]))])
}

const nodes = {}
const groups = []
for (const [title, items] of ICON_SET) {
  groups.push([title, items.map(([meaning]) => meaning)])
  for (const [meaning, file] of items) nodes[meaning] = shapesOf(file)
}

const output = `// Generated by scripts/generate-icons.mjs from scripts/icon-set.mjs (shapes from Lucide, ISC licence). Do not edit: change the set and run \`npm run icons\`.

export type IconShape = readonly [tag: "path" | "circle" | "rect" | "line" | "polyline" | "polygon" | "ellipse", attributes: Readonly<Record<string, string>>]

/** The shapes of each meaning, drawn on a 24 × 24 grid. */
export const ICON_NODES = ${JSON.stringify(nodes, null, 2)} as const satisfies Record<string, readonly IconShape[]>

/** The meanings by group, in the order the Catalogue shows them. */
export const ICON_GROUPS = ${JSON.stringify(groups, null, 2)} as const

/** Meanings that point somewhere: mirrored where the text runs right to left. */
export const MIRRORED_ICONS: readonly string[] = ${JSON.stringify(MIRRORED)}
`
writeFileSync(join(import.meta.dirname, "..", "src", "lib", "icon-nodes.ts"), output)
console.log(`${Object.keys(nodes).length} icons in ${groups.length} groups written to src/lib/icon-nodes.ts`)
